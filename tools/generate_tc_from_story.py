#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
tools/generate_tc_from_story.py — Large Action Model (LAM) Script Generator
Inspired by LaVague: Converts natural language user stories into Clean POM test scripts.
Supports configurable packages, dynamic Page Class discovery, and cross-platform execution.
"""

import sys
import os
import re
import glob
import argparse

# Enforce UTF-8 stdout encoding for Windows console compatibility
if hasattr(sys.stdout, 'reconfigure'):
    try:
        sys.stdout.reconfigure(encoding='utf-8')
        sys.stderr.reconfigure(encoding='utf-8')
    except Exception:
        pass

DEFAULT_PAGE_MAP = {
    "login": "LoginPage",
    "auth": "LoginPage",
    "user": "UserAdminPage",
    "common": "CommonCategoryPage",
    "category": "CategoryPage",
    "planning": "PlanningPage",
    "report": "ReportPage",
    "search": "SearchPage",
}


def detect_project_package(repo_root="."):
    """Detects the standard package prefix from existing project structure or guide."""
    # 1. Check PROJECT_AI_GUIDE.md for explicit package hints
    guide_path = os.path.join(repo_root, "PROJECT_AI_GUIDE.md")
    if os.path.isfile(guide_path):
        try:
            with open(guide_path, "r", encoding="utf-8", errors="ignore") as f:
                content = f.read()
                m = re.search(r'import\s+([\w\.]+)\.pages\.', content)
                if m:
                    return f"{m.group(1)}.pages"
        except Exception:
            pass

    # 2. Check existing Keywords/ directory
    keywords_dir = os.path.join(repo_root, "Keywords")
    if os.path.isdir(keywords_dir):
        for root, _, files in os.walk(keywords_dir):
            for file in files:
                if file.endswith(".groovy"):
                    rel = os.path.relpath(root, keywords_dir)
                    parts = [p for p in rel.replace("\\", "/").split("/") if p and p != "."]
                    if parts:
                        return ".".join(parts)

    return "pages"


def discover_page_classes(repo_root="."):
    """Discovers available Page classes dynamically from workspace files."""
    pages = dict(DEFAULT_PAGE_MAP)
    search_dirs = [
        os.path.join(repo_root, "Keywords"),
        os.path.join(repo_root, "pages"),
        os.path.join(repo_root, "src", "pages"),
        os.path.join(repo_root, "tests", "pages")
    ]
    for d in search_dirs:
        if os.path.isdir(d):
            for f in glob.glob(os.path.join(d, "**", "*Page*.*"), recursive=True):
                base = os.path.basename(f)
                name, _ = os.path.splitext(base)
                clean_key = name.lower().replace("page", "").replace("_", "")
                if clean_key:
                    pages[clean_key] = name
    return pages


def generate_script(story, module_name="CategoryPage", tc_name="TC_AutoGenerated", package_name=None, repo_root="."):
    detected_package = package_name or detect_project_package(repo_root)
    discovered_pages = discover_page_classes(repo_root)

    # Normalize module name
    mod_clean = module_name.lower().replace("page", "").replace("_", "")
    target_page = discovered_pages.get(mod_clean, f"{module_name[:1].upper()}{module_name[1:]}")
    if not target_page.endswith("Page"):
        target_page += "Page"

    # Detect action intent from story keywords
    story_lower = story.lower()
    is_delete = any(k in story_lower for k in ["xóa", "xoa", "delete", "remove"])
    is_edit = any(k in story_lower for k in ["sửa", "sua", "chỉnh sửa", "chinh sua", "edit", "update"])
    is_search = any(k in story_lower for k in ["tìm", "tim", "tìm kiếm", "tim kiem", "search", "filter"])
    is_add = not (is_delete or is_edit or is_search) or any(k in story_lower for k in ["thêm", "them", "tạo mới", "tao moi", "add", "create"])

    lines = []
    lines.append("// ===========================================================================")
    lines.append(f"// Test Case: {tc_name}")
    lines.append(f"// Requirement: {story}")
    lines.append("// Architecture: Clean POM & Flat Architecture (Generated by LaVague LAM Engine)")
    lines.append("// ===========================================================================")
    lines.append("")
    lines.append(f"import {detected_package}.LoginPage")
    lines.append(f"import {detected_package}.{target_page}")
    lines.append("")
    lines.append("// 1. Ensure system authentication session")
    lines.append("LoginPage.ensureLoggedIn()")
    lines.append("")
    lines.append("// 2. Initialize dynamic idempotent test data")
    lines.append('String uniqueCode = "AUTO_" + System.currentTimeMillis()')
    lines.append('String testName = "Test Entity " + uniqueCode')
    lines.append("")

    if is_add:
        lines.append("// 3. Execute entity creation workflow")
        lines.append(f"{target_page}.openCreateModal()")
        lines.append(f"{target_page}.fillCreateForm(uniqueCode, testName)")
        lines.append(f"{target_page}.confirmCreate()")
        lines.append(f"{target_page}.verifyCreateSuccess(uniqueCode)")

    elif is_edit:
        lines.append("// 3. Execute entity update workflow")
        lines.append('String updatedName = testName + " [Updated]"')
        lines.append(f"{target_page}.searchKeyword(uniqueCode)")
        lines.append(f"{target_page}.openEditFirstRow()")
        lines.append(f"{target_page}.updateName(updatedName)")
        lines.append(f"{target_page}.confirmEdit()")
        lines.append(f"{target_page}.verifyEditSuccess(updatedName)")

    elif is_delete:
        lines.append("// 3. Execute entity deletion workflow")
        lines.append(f"{target_page}.searchKeyword(uniqueCode)")
        lines.append(f"{target_page}.clickDeleteFirstRow()")
        lines.append(f"{target_page}.confirmDelete()")
        lines.append(f"{target_page}.verifyDeleted(uniqueCode)")

    elif is_search:
        lines.append("// 3. Execute entity search/filter workflow")
        lines.append(f"{target_page}.searchKeyword(uniqueCode)")
        lines.append(f"{target_page}.verifySearchResults(uniqueCode)")

    lines.append("")
    lines.append("// 4. Automated idempotent teardown cleanup")
    lines.append(f"// {target_page}.teardown(uniqueCode)")
    lines.append("")

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="LaVague-style LAM Script Generator for Clean POM Automation")
    parser.add_argument("--story", "-s", required=True, help="User story or Acceptance Criteria (natural language)")
    parser.add_argument("--module", "-m", default="CategoryPage", help="Target Page Class or Module name")
    parser.add_argument("--name", "-n", default="TC_AutoGenerated", help="Test Case name")
    parser.add_argument("--package", "-p", default=None, help="Base package name for imports (e.g. 'com.company.pages')")
    parser.add_argument("--out", "-o", default=None, help="Output file path (optional)")
    args = parser.parse_args()

    script_content = generate_script(
        story=args.story,
        module_name=args.module,
        tc_name=args.name,
        package_name=args.package
    )

    if args.out:
        out_dir = os.path.dirname(args.out)
        if out_dir:
            os.makedirs(out_dir, exist_ok=True)
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(script_content)
        print(f"Generated Clean POM script successfully saved to: {args.out}")
    else:
        print(script_content)


if __name__ == "__main__":
    main()
